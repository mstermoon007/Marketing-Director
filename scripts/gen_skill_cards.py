def _card(cid, name, scenario, principle, steps, kpi, content, category):
    return {
        "id": cid,
        "name": name,
        "category": category,
        "channels": [GENERIC],
        "industry": GENERIC,
        "scenario": scenario,
        "principle": principle,
        "steps": steps,
        "kpi": kpi,
        "content": content,
    }


def build_cards():
    cards = []
    for cid, name, scenario, principle, steps, kpi, content in FRAMEWORK_CARDS:
        cards.append(_card(cid, name, scenario, principle, steps, kpi, content, CATEGORY_FW))
    for cid, name, scenario, principle, steps, kpi, content in TOOL_CARDS:
        cards.append(_card(cid, name, scenario, principle, steps, kpi, content, CATEGORY_TOOL))
    for cid, name, scenario, principle, steps, kpi, content in KPI_CARDS:
        cards.append(_card(cid, name, scenario, principle, steps, kpi, content, CATEGORY_KPI))
    return cards


def main():
    JSONL.parent.mkdir(parents=True, exist_ok=True)
    existing = set()
    if JSONL.exists():
        with JSONL.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    existing.add(json.loads(line).get("id"))
                except json.JSONDecodeError:
                    continue

    cards = build_cards()
    new_cards = [c for c in cards if c["id"] not in existing]
    if not new_cards:
        print(f"无需追加：{len(cards)} 张理论/工具/KPI 卡均已存在。")
        return

    with JSONL.open("a", encoding="utf-8") as f:
        for c in new_cards:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    print(f"已追加 {len(new_cards)} 张卡（理论 {CATEGORY_FW} / 工具 {CATEGORY_TOOL} / KPI {CATEGORY_KPI}）。")
    print(f"方法库当前约 {len(existing) + len(new_cards)} 张卡。")


if __name__ == "__main__":
    sys.exit(main())
