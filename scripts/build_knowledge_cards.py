def _fill(template: str, industry: str, channel: str) -> str:
    return template.replace("{industry}", industry).replace("{channel}", channel)


def build_cards() -> list[dict]:
    cards: list[dict] = []
    seq = 0

    # 1) 可扩展模板 × 行业 × 渠道
    for tpl in EXPANDABLE_TEMPLATES:
        channels = tpl["channels"]
        for industry in INDUSTRIES:
            # 每个行业取该模板适用的渠道子集；为控制体量，每行业最多取 4 个渠道
            chosen = channels[:4]
            for channel in chosen:
                seq += 1
                name = _fill(tpl["name"], industry, channel)
                content = _fill(tpl["content"], industry, channel)
                steps = [_fill(s, industry, channel) for s in tpl["steps"]]
                cards.append({
                    "id": f"card_{seq:04d}",
                    "name": name,
                    "category": tpl["category"],
                    "channels": [channel],
                    "industry": industry,
                    "scenario": "通用",
                    "principle": tpl["principle"],
                    "steps": steps,
                    "kpi": tpl["kpi"],
                    "content": content,
                })

    # 2) 通用框架单卡
    for g in GENERIC_CARDS:
        seq += 1
        cards.append({
            "id": f"card_{seq:04d}",
            "name": g["name"],
            "category": g["category"],
            "channels": ["通用"],
            "industry": "通用",
            "scenario": "通用",
            "principle": g["principle"],
            "steps": g["steps"],
            "kpi": g["kpi"],
            "content": g["content"],
        })

    return cards


def main() -> None:
    cards = build_cards()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PATH.open("w", encoding="utf-8") as f:
        for c in cards:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    print(f"生成完毕：{len(cards)} 张营销方法卡片 → {OUT_PATH}")
    # 简单统计
    from collections import Counter
    cat_counter = Counter(c["category"] for c in cards)
    ind_counter = Counter(c["industry"] for c in cards)
    print("按类别：", dict(cat_counter))
    print("行业覆盖数：", len(ind_counter))


if __name__ == "__main__":
    main()
